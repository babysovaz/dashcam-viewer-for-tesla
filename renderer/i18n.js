let LANG = (() => {
  try { const s = localStorage.getItem("tcv.lang"); if (I18N[s]) return s; } catch {}
  return (navigator.language || "en").toLowerCase().startsWith("fr") ? "fr" : "en";
})();
/** Translate a key, filling {placeholders}. Falls back to French, then to the key itself. */
function t(key, vars = {}) {
  const s = I18N[LANG][key] ?? I18N.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, n) => vars[n] ?? "");
}
/** Locale for dates: French, or the OS English variant (en-US gets AM/PM, others 24 h). */
const locale = () => LANG === "fr" ? "fr-FR" : (/^en-/i.test(navigator.language || "") ? navigator.language : "en-GB");
/** Fill every element tagged data-i18n / data-i18n-title / data-i18n-ph with the current language. */
function applyStaticText() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll("[data-i18n]")) el.innerHTML = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}
